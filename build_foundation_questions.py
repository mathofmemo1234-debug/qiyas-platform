    print(f"Loaded {len(all_qs)} existing questions.")

    # Remove previous foundation questions if any, or update them
    existing_non_f = [q for q in all_qs if not q.get('is_foundation')]

    max_id = max([q.get('id', 0) for q in existing_non_f]) if existing_non_f else 0

